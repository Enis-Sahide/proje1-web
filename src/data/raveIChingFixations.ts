/**
 * Resmi Rave I'Ching kuralına göre gezegenin o çizgiyle rezonansını (Yücelim / Düşüş / Yok) tespit eder.
 */
export function getLineFixation(gate: number, line: number, planet: PlanetCode): 'exalted' | 'detriment' | 'none' {
  const gateData = RAVE_ICHING_FIXATIONS[gate];
  if (!gateData) return 'none';
  const lineData = gateData[line];
  if (!lineData) return 'none';

  if (lineData.exalted && lineData.exalted.includes(planet)) {
    return 'exalted';
  }
  if (lineData.detriment && lineData.detriment.includes(planet)) {
    return 'detriment';
  }
  return 'none';
}
